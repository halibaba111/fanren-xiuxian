export class CharacterRegistry {
    public static all(): readonly CharacterDefinition[] {
        return CHARACTER_DEFINITIONS;
    }

    public static get(npcId: string): CharacterDefinition | null {
        return CHARACTER_DEFINITIONS.find((entry) => entry.npcId === npcId) ?? null;
    }

    public static companions(): CharacterDefinition[] {
        return CHARACTER_DEFINITIONS.filter((entry) => entry.recruitable);
    }
}
