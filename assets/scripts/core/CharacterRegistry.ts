import {
    CharacterDefinition,
    CompanionRole,
    RelationshipType,
} from './StoryTypes';

function companion(
    npcId: string,
    name: string,
    role: string,
    faction: string,
    relationshipType: RelationshipType,
    supportRole: CompanionRole,
    supportDescription: string,
    publicGoal: string,
    privateGoal: string,
    boundary: string,
    independentAction: string,
    recruitChapter: string,
    requiredFlags: string[],
    options: Partial<CharacterDefinition> = {},
): CharacterDefinition {
    return {
        npcId,
        name,
        role,
        faction,
        relationshipType,
        romanceable: relationshipType === 'romance',
        recruitable: true,
        publicGoal,
        privateGoal,
        boundary,
        independentAction,
        supportRole,
        supportDescription,
        recruitChapter,
        summonUnlockContent: `summon_${npcId}`,
        requiredFlags,
        ...options,
    };
}

